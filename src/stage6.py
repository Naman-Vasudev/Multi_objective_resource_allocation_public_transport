def build_schedules(routes, dem) -> tuple[list, MD.Instance]:
    scs, k1, k3 = _scenarios(), *_kappas()
    inst0 = MD.build_instance(routes, dem, _cfg())
    out = [S.baseline(inst0), S.baseline_peak(inst0)]
    for a in P.SIM_ALPHAS:
        inst = MD.build_instance(routes, dem, _cfg(alpha=a))
        for nm in GP_NAMES:
            s, st = S.from_gp(inst, f"{nm} (α={a:g})", scs[nm], k1, a, k3)
            if st != "Optimal":
                raise RuntimeError(f"{nm} alpha={a}: {st}")
            out.append(s)
    # robust variant (D47): headline policy planned at alpha = 0 on the WIDER uncertainty set (spreads x OOS_WIDEN)
    dem_w = widened_demand(dem, P.OOS_WIDEN)
    inst_w = MD.build_instance(routes, dem_w, _cfg(alpha=0.0))
    s, st = S.from_gp(inst_w, ROBUST_NAME, scs[P.SIM_POLICY], k1, 0.0, k3)
    if st != "Optimal":
        raise RuntimeError(f"robust variant: {st}")
    out.append(s)
    hw, info = S.knee_point(P.OUT / "pareto_eps.csv", P.OUT / "pareto_nsga2.csv", P.OUT_TAB / "pareto_payoff.csv")
    out.append(S.from_headways(inst0, "KNEE (Pareto front)", hw, P.PARETO_ALPHA, f"knee of front ({info['src']})"))
    log.info("knee point from %s: Z1 %.0f Z2 %.0f Z3 %.0f (distance to ideal %.3f, normalised)",
             info["src"], info["Z1"], info["Z2"], info["Z3"], info["dist_to_ideal"])
    return out, inst0


def compare(routes, dem) -> dict:
    scheds, inst = build_schedules(routes, dem)
    L, M, U = S.tfn_arrays(inst, dem)
    D = S.draw_demand(L, M, U)
    summ, route_rows, means = [], [], {}
    for s in scheds:
        per, rt = S.simulate(inst, s, D)
        summ.append(S.summarise(s.name, per))
        route_rows.append(rt.assign(schedule=s.name))
        means[s.name] = _means(per)
        means[s.name]["overflow_share_samples"] = per["overflow_share"]
    summary = pd.concat(summ, ignore_index=True)
    summary.insert(0, "label", "synthetic demand, illustrative")
    summary.to_csv(P.OUT / "simulation_summary.csv", index=False)
    pd.concat(route_rows, ignore_index=True).to_csv(P.OUT_TAB / "simulation_route_LF.csv", index=False)

    b = means["Baseline"]
    tr = []
    for s in scheds:
        m = means[s.name]
        row = dict(schedule=s.name, source=s.source, alpha=s.alpha)
        for k in KEY:
            row[f"{k}"] = m[k]
            row[f"pct_{k}"] = (100 * (m[k] - b[k]) / b[k]) if b[k] else float("nan")
        row["P_overflow_gt_5pct"] = m["P_overflow_gt_5pct"]
        tr.append(row)
    trade = pd.DataFrame(tr)
    trade.to_csv(P.OUT_TAB / "simulation_tradeoffs.csv", index=False)
    return dict(scheds=scheds, inst=inst, D=D, trade=trade, means=means)


