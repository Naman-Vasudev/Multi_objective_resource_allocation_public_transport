log = logging.getLogger("stage6")
GP_NAMES = ("P-PASSENGER", "P-OPERATOR", "P-EQUITY", "P-BALANCED")
KEY = {"mean_wait_min": "expected wait", "overflow_pax": "overflow", "vehicle_km": "vehicle-km",
       "fleet_used": "fleet used", "gini_LF": "load-factor Gini", "equity_excess_min": "headway above cap"}


def _cfg(**kw) -> P.ModelConfig:
    base = dict(fmax_mode=P.SIM_FMAX_MODE, alpha=P.PARETO_ALPHA)
    base.update(kw)
    return P.ModelConfig(**base)


ROBUST_NAME = f"{P.SIM_POLICY} ROBUST (α=0, spreads ×{P.OOS_WIDEN:g})"


def _scenarios() -> dict:
    return {s["name"]: s for s in G.load_config()["scenarios"]}


def _kappas() -> tuple[float, float]:
    c = G.load_config()
    return c["kappa1"], c.get("kappa3", 0.0)


def widened_demand(dem: pd.DataFrame, w: float) -> pd.DataFrame:
    """Same modal demand M, both TFN spreads stretched by w (L clipped at 0)."""
    d = dem.copy()
    d["L"] = np.maximum(0.0, d.M - w * (d.M - d.L))
    d["U"] = d.M + w * (d.U - d.M)
    return d


def _means(per: dict) -> dict:
    out = {k: float(v.mean()) for k, v in per.items()}
    out["P_overflow_gt_5pct"] = float((per["overflow_share"] > P.SIM_OVERFLOW_THRESHOLD).mean())
    return out


