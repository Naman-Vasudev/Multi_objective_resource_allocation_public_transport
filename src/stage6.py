def policy_vs_baseline(routes, dem, cfg: P.ModelConfig, policy: str = P.SIM_POLICY, D=None,
                       shock_sd: float = P.SIM_SHOCK_SD, widen: float = 1.0) -> dict:
    """Optimise `policy` under cfg; simulate it and the baseline on the same draws. Infeasible -> reason string."""
    inst = MD.build_instance(routes, dem, cfg)
    issues = MD.presolve_report(inst)
    row = dict(B_eff=cfg.B_eff)
    if issues:
        return dict(row, feasible=False, reason="; ".join(issues))
    if D is None:
        L, M, U = S.tfn_arrays(inst, dem, widen)
        D = S.draw_demand(L, M, U, shock_sd=shock_sd)
    k1, k3 = _kappas()
    s, st = S.from_gp(inst, policy, _scenarios()[policy], k1, cfg.alpha, k3)
    mb = _means(S.simulate(inst, S.baseline(inst), D)[0])
    mo = _means(S.simulate(inst, s, D)[0])
    row.update(feasible=True, reason="", status=st)
    for k in ("mean_wait_min", "overflow_pax", "vehicle_km", "fleet_used", "P_overflow_gt_5pct"):
        row[f"base_{k}"] = mb[k]
        row[f"opt_{k}"] = mo[k]
    row["wait_improvement_pct"] = 100 * (mb["mean_wait_min"] - mo["mean_wait_min"]) / mb["mean_wait_min"]
    return row


def sensitivity(routes, dem) -> dict:
    rows = []

    def add(factor, value, **kw):
        dem_k = kw.pop("dem_scale", None)
        d = dem
        if dem_k is not None:
            d = dem.copy()
            d[["L", "M", "U"]] = d[["L", "M", "U"]] * dem_k
        r = policy_vs_baseline(routes, d, _cfg(**kw))
        rows.append(dict(factor=factor, value=value, **r))
        log.info("sensitivity %s=%s: %s", factor, value,
                 f"wait improvement {r['wait_improvement_pct']:.2f}%" if r["feasible"] else "INFEASIBLE")

    for k in (0.8, 0.9, 1.0, 1.1, 1.2):
        add("demand level", k, dem_scale=k)
    for C in (50, 60, 70, 80):
        add("capacity C", C, C=C)
    for v in (18, 22, 26):
        add("speed v", v, speed_kmh=float(v))
    for s in (0.0, 0.08, 0.1, 0.2):
        add("spare ratio s", s, spare_ratio=s)
    for lay in (0.05, 0.10, 0.15):        # D46: recovery time is uncertain, so it is tested, not assumed
        add("layover", lay, layover_frac=lay)
    oat = pd.DataFrame(rows)
    oat.to_csv(P.OUT / "sensitivity_oat.csv", index=False)

    alpha = pd.DataFrame([dict(alpha=a, **policy_vs_baseline(routes, dem, _cfg(alpha=a)))
                          for a in G.load_config()["alphas"]])
    alpha.to_csv(P.OUT / "sensitivity_alpha.csv", index=False)

    base_B = P.ModelConfig().B_eff
    fleet_rows = []
    for cut in (0.0, 0.05, 0.10):
        target = math.floor(base_B * (1 - cut))
        s_ratio = 1 - target / P.FLEET_B
        r = policy_vs_baseline(routes, dem, _cfg(spare_ratio=s_ratio))
        fleet_rows.append(dict(fleet_cut=cut, **r))
    fleet = pd.DataFrame(fleet_rows)
    fleet.to_csv(P.OUT / "sensitivity_fleet.csv", index=False)
    return dict(oat=oat, alpha=alpha, fleet=fleet)


def out_of_sample(routes, dem, scheds, inst) -> pd.DataFrame:
    """Schedules optimised with the default TFN, evaluated in-sample and on a wider distribution."""
    L, M, U = S.tfn_arrays(inst, dem)
    D_in = S.draw_demand(L, M, U)
    Lw, Mw, Uw = S.tfn_arrays(inst, dem, widen=P.OOS_WIDEN)
    D_out = S.draw_demand(Lw, Mw, Uw, seed=P.SIM_SEED + 1, shock_sd=P.OOS_SHOCK_SD)
    rows = []
    for s in scheds:
        for lab, D in (("in-sample", D_in), ("out-of-sample (wider)", D_out)):
            m = _means(S.simulate(inst, s, D)[0])
            rows.append(dict(schedule=s.name, sample=lab, mean_wait_min=m["mean_wait_min"],
                             overflow_pax=m["overflow_pax"], P_overflow_gt_5pct=m["P_overflow_gt_5pct"]))
    oos = pd.DataFrame(rows)
    oos.to_csv(P.OUT / "sensitivity_out_of_sample.csv", index=False)
    return oos


